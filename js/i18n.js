  var currentLang = 'en';
  var onLangChange = [];

  function translate(lang, key) {
    var pack = I18N[lang] || I18N.en;
    return (pack[key] != null) ? pack[key] : (I18N.en[key] || '');
  }

  function applyLang(lang) {
    if (!I18N[lang]) lang = 'en';
    currentLang = lang;
    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var val = translate(lang, key);
      if (val) el.textContent = val;
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      var val = translate(lang, key);
      if (val) el.innerHTML = val;
    });

    document.querySelectorAll('.lang__btn').forEach(function (b) {
      var active = b.getAttribute('data-lang') === lang;
      b.classList.toggle('is-active', active);
      b.setAttribute('aria-pressed', active ? 'true' : 'false');
    });

    try { localStorage.setItem('lang', lang); } catch (e) {}

    onLangChange.forEach(function (fn) { try { fn(lang); } catch (e) {} });
  }

  function detect() {
    var stored = null;
    try { stored = localStorage.getItem('lang'); } catch (e) {}
    if (stored === 'en' || stored === 'id') return stored;
    var nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    return nav.indexOf('id') === 0 ? 'id' : 'en';
  }

  window.__i18n = {
    t: function (key) { return translate(currentLang, key); },
    get lang() { return currentLang; },
    apply: applyLang,
    onChange: function (fn) { onLangChange.push(fn); }
  };

  applyLang(detect());
